-- RF1
CREATE TABLE conductores (
    id_conductor      NUMBER GENERATED BY DEFAULT AS IDENTITY,
    nombre            VARCHAR2(60)  NOT NULL,
    apellidos         VARCHAR2(80)  NOT NULL,
    universidad       VARCHAR2(100) NOT NULL,
    programa          VARCHAR2(100) NOT NULL,
    correo            VARCHAR2(120) NOT NULL,
    celular           VARCHAR2(10)  NOT NULL,
    documento         VARCHAR2(20)  NOT NULL,
    CONSTRAINT pk_conductores PRIMARY KEY (id_conductor),
    CONSTRAINT uq_conductores_correo UNIQUE (correo),
    CONSTRAINT uq_conductores_documento UNIQUE (documento),
    CONSTRAINT ck_conductores_correo CHECK (correo LIKE '%_@_%._%'),
    CONSTRAINT ck_conductores_celular CHECK (REGEXP_LIKE(celular, '^[0-9]{10}$'))
);

-- Necesaria para RF4 y RF6 (solicitudes y pasajeros confirmados)
CREATE TABLE pasajeros (
    id_pasajero       NUMBER GENERATED BY DEFAULT AS IDENTITY,
    nombre            VARCHAR2(60)  NOT NULL,
    apellidos         VARCHAR2(80)  NOT NULL,
    universidad       VARCHAR2(100) NOT NULL,
    programa          VARCHAR2(100) NOT NULL,
    correo            VARCHAR2(120) NOT NULL,
    celular           VARCHAR2(10)  NOT NULL,
    documento         VARCHAR2(20)  NOT NULL,
    CONSTRAINT pk_pasajeros PRIMARY KEY (id_pasajero),
    CONSTRAINT uq_pasajeros_correo UNIQUE (correo),
    CONSTRAINT uq_pasajeros_documento UNIQUE (documento),
    CONSTRAINT ck_pasajeros_correo CHECK (correo LIKE '%_@_%._%'),
    CONSTRAINT ck_pasajeros_celular CHECK (REGEXP_LIKE(celular, '^[0-9]{10}$'))
);

-- RF2
CREATE TABLE vehiculos (
    id_vehiculo       NUMBER GENERATED BY DEFAULT AS IDENTITY,
    id_conductor      NUMBER        NOT NULL,
    placa             VARCHAR2(6)   NOT NULL,
    marca             VARCHAR2(40)  NOT NULL,
    modelo            VARCHAR2(40)  NOT NULL,
    anio              NUMBER(4)     NOT NULL,
    color             VARCHAR2(30)  NOT NULL,
    cupos             NUMBER(2)     NOT NULL,
    CONSTRAINT pk_vehiculos PRIMARY KEY (id_vehiculo),
    CONSTRAINT fk_vehiculos_conductor FOREIGN KEY (id_conductor)
        REFERENCES conductores (id_conductor),
    CONSTRAINT uq_vehiculos_placa UNIQUE (placa),
    CONSTRAINT ck_vehiculos_placa CHECK (REGEXP_LIKE(placa, '^[A-Z]{3}[0-9]{2}[0-9A-Z]$')),
    CONSTRAINT ck_vehiculos_anio CHECK (anio BETWEEN 1980 AND 2100),
    CONSTRAINT ck_vehiculos_cupos CHECK (cupos BETWEEN 1 AND 8)
);

-- RF3 y RF5. El conductor se obtiene a traves del vehiculo: guardarlo aqui
-- tambien crearia la dependencia id_vehiculo -> id_conductor y romperia BCNF.
CREATE TABLE viajes (
    id_viaje          NUMBER GENERATED BY DEFAULT AS IDENTITY,
    id_vehiculo       NUMBER        NOT NULL,
    fecha_salida      DATE          NOT NULL,
    punto_origen      VARCHAR2(200) NOT NULL,
    destino           VARCHAR2(200) NOT NULL,
    ruta_general      VARCHAR2(500) NOT NULL,
    tarifa            NUMBER(10,2)  NOT NULL,
    cupos_disponibles NUMBER(2)     NOT NULL,
    estado            VARCHAR2(12)  DEFAULT 'PROGRAMADO' NOT NULL,
    distancia_km      NUMBER(6,2),
    duracion_min      NUMBER(5),
    CONSTRAINT pk_viajes PRIMARY KEY (id_viaje),
    CONSTRAINT fk_viajes_vehiculo FOREIGN KEY (id_vehiculo)
        REFERENCES vehiculos (id_vehiculo),
    CONSTRAINT ck_viajes_tarifa CHECK (tarifa >= 0),
    CONSTRAINT ck_viajes_cupos CHECK (cupos_disponibles >= 0),
    CONSTRAINT ck_viajes_estado CHECK (estado IN ('PROGRAMADO', 'EN_CURSO', 'COMPLETADO', 'CANCELADO')),
    CONSTRAINT ck_viajes_distancia CHECK (distancia_km > 0),
    CONSTRAINT ck_viajes_duracion CHECK (duracion_min > 0)
);

-- RF3 (paradas iniciales) y RF4 (punto de recogida aceptado)
CREATE TABLE paradas (
    id_parada         NUMBER GENERATED BY DEFAULT AS IDENTITY,
    id_viaje          NUMBER        NOT NULL,
    direccion         VARCHAR2(200) NOT NULL,
    localidad         VARCHAR2(60)  NOT NULL,
    orden             NUMBER(3)     NOT NULL,
    CONSTRAINT pk_paradas PRIMARY KEY (id_parada),
    CONSTRAINT fk_paradas_viaje FOREIGN KEY (id_viaje)
        REFERENCES viajes (id_viaje) ON DELETE CASCADE,
    CONSTRAINT uq_paradas_direccion UNIQUE (id_viaje, direccion),
    CONSTRAINT uq_paradas_orden UNIQUE (id_viaje, orden),
    CONSTRAINT ck_paradas_orden CHECK (orden > 0)
);

-- RF4 y RF6
CREATE TABLE solicitudes (
    id_solicitud      NUMBER GENERATED BY DEFAULT AS IDENTITY,
    id_viaje          NUMBER        NOT NULL,
    id_pasajero       NUMBER        NOT NULL,
    punto_recogida    VARCHAR2(200) NOT NULL,
    localidad         VARCHAR2(60)  NOT NULL,
    fecha_solicitud   DATE          DEFAULT SYSDATE NOT NULL,
    estado            VARCHAR2(10)  DEFAULT 'PENDIENTE' NOT NULL,
    CONSTRAINT pk_solicitudes PRIMARY KEY (id_solicitud),
    CONSTRAINT fk_solicitudes_viaje FOREIGN KEY (id_viaje)
        REFERENCES viajes (id_viaje),
    CONSTRAINT fk_solicitudes_pasajero FOREIGN KEY (id_pasajero)
        REFERENCES pasajeros (id_pasajero),
    CONSTRAINT ck_solicitudes_estado CHECK (estado IN ('PENDIENTE', 'ACEPTADA', 'RECHAZADA', 'CANCELADA'))
);

-- Un pasajero solo puede tener una solicitud activa por viaje, pero puede
-- volver a solicitar si la anterior fue rechazada o cancelada.
CREATE UNIQUE INDEX ux_solicitudes_activa ON solicitudes (
    CASE WHEN estado IN ('PENDIENTE', 'ACEPTADA') THEN id_viaje END,
    CASE WHEN estado IN ('PENDIENTE', 'ACEPTADA') THEN id_pasajero END
);

-- Indices para las llaves foraneas
CREATE INDEX ix_vehiculos_conductor ON vehiculos (id_conductor);
CREATE INDEX ix_viajes_vehiculo ON viajes (id_vehiculo);
CREATE INDEX ix_solicitudes_viaje ON solicitudes (id_viaje);
CREATE INDEX ix_solicitudes_pasajero ON solicitudes (id_pasajero);
